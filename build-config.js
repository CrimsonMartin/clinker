const fs = require('fs');
const path = require('path');

// Load environment variables from .env file (optional - defaults are used without one)
require('dotenv').config({ quiet: true });

const DEFAULT_API_BASE_URL = 'https://clinker.lanerate.io';
const DEFAULT_DONATION_URL = 'https://www.buymeacoffee.com/YOUR_USERNAME';

// Normalize and validate the API base URL (origin plus optional path, no trailing slash)
function resolveApiBaseUrl(raw) {
  const value = (raw || '').trim() || DEFAULT_API_BASE_URL;
  let url;
  try {
    url = new URL(value);
  } catch (error) {
    throw new Error(`API_BASE_URL is not a valid URL: ${value}`);
  }
  if (url.protocol !== 'https:' && url.protocol !== 'http:') {
    throw new Error(`API_BASE_URL must use http or https: ${value}`);
  }
  if (url.protocol === 'http:' && !['localhost', '127.0.0.1', '[::1]'].includes(url.hostname)) {
    console.warn(`\nWarning: API_BASE_URL uses plain http (${value}). Use https outside local development.`);
  }
  return (url.origin + url.pathname).replace(/\/+$/, '');
}

function getConfig() {
  const apiBaseUrl = resolveApiBaseUrl(process.env.API_BASE_URL);
  return {
    apiBaseUrl,
    apiOrigin: new URL(apiBaseUrl).origin,
    donationUrl: (process.env.DONATION_URL || '').trim() || DEFAULT_DONATION_URL
  };
}

function generateConfigFile(config) {
  const clinkerConfig = { apiBaseUrl: config.apiBaseUrl };
  const appConfig = { donationUrl: config.donationUrl };

  return `// Citation Linker configuration - Generated by build-config.js from .env
// DO NOT EDIT THIS FILE DIRECTLY - edit .env instead and run 'npm run build:config'

// Sync API configuration
const CLINKER_CONFIG = ${JSON.stringify(clinkerConfig, null, 2)};

// App configuration object
const APP_CONFIG = ${JSON.stringify(appConfig, null, 2)};

// Make config available globally for the auth and sync managers
if (typeof window !== 'undefined') {
  window.CLINKER_CONFIG = CLINKER_CONFIG;
  window.APP_CONFIG = APP_CONFIG;
  window.appConfig = APP_CONFIG;
}

// Export for use in other modules (Node.js/testing)
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { CLINKER_CONFIG, APP_CONFIG, clinkerConfig: CLINKER_CONFIG, appConfig: APP_CONFIG };
}
`;
}

function main() {
  const config = getConfig();

  if (config.donationUrl.includes('YOUR_USERNAME')) {
    console.warn('\nWarning: DONATION_URL not configured or contains placeholder.');
    console.warn('Set DONATION_URL in your .env file to your Buy Me a Coffee URL.');
  }

  const configPath = path.join(__dirname, 'api', 'config.js');
  fs.mkdirSync(path.dirname(configPath), { recursive: true });
  fs.writeFileSync(configPath, generateConfigFile(config));

  console.log(`Configuration generated at api/config.js (API: ${config.apiBaseUrl})`);
}

if (require.main === module) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}

module.exports = { getConfig, resolveApiBaseUrl, generateConfigFile, DEFAULT_API_BASE_URL };
